def _draw_floor_plan(c, boundary_points_ft, obstacles, rooms, plan_x, plan_y, plan_w, plan_h, sheet_type="Zoning Layout"):
    if not boundary_points_ft:
        return
    xs = [p[0] for p in boundary_points_ft]
    ys = [p[1] for p in boundary_points_ft]
    bw, bh = max(xs) - min(xs), max(ys) - min(ys)
    if bw <= 0 or bh <= 0:
        return

    # Title/scale header at the top of the box, and dimension lines along the
    # drawing, both take a slice of the box's own available space rather than
    # the full box — real footprints (esp. a single confirmed region) are
    # often much wider than tall relative to a portrait sheet, so the plan
    # alone would otherwise leave a large, unlabelled blank area above/below it.
    header_h = 20 * mm
    dim_h = 12 * mm
    c.setFont("Helvetica-Bold", 11)
    c.setFillColor(black)
    c.drawString(plan_x + 4, plan_y + plan_h - 14, f"FLOOR PLAN — {sheet_type.upper()}")
    c.setFont("Helvetica", 7.5)
    c.setFillColor(HexColor("#444444"))
    c.drawString(plan_x + 4, plan_y + plan_h - 24, "SCALE : N.T.S.")

    draw_x, draw_y = plan_x, plan_y + dim_h
    draw_w, draw_h = plan_w, plan_h - header_h - dim_h

    # A confirmed region is often much wider than tall (or vice versa) relative
    # to this portrait sheet's drawing area. Rather than fit it as-is and leave
    # most of the sheet blank, rotate 90° whenever that orientation lets the
    # plan actually use more of the available area — the same call a drafter
    # fitting a plan to a sheet would make. Only geometry is rotated; room/
    # dimension labels are still drawn upright via drawCentredString, so text
    # stays horizontal and readable either way.
    scale_normal = min(draw_w / bw, draw_h / bh)
    scale_rotated = min(draw_w / bh, draw_h / bw)
    rotated = scale_rotated > scale_normal * 1.1
    scale = (scale_rotated if rotated else scale_normal) * 0.94
    min_x, min_y = min(xs), min(ys)

    if rotated:
        ox = draw_x + (draw_w - bh * scale) / 2
        oy = draw_y + (draw_h - bw * scale) / 2

        def tx(pt):
            return (ox + (pt[1] - min_y) * scale, oy + (pt[0] - min_x) * scale)
    else:
        ox = draw_x + (draw_w - bw * scale) / 2 - min_x * scale
        oy = draw_y + (draw_h - bh * scale) / 2 - min_y * scale

        def tx(pt):
            return (ox + pt[0] * scale, oy + pt[1] * scale)

    c.setStrokeColor(black)
    c.setLineWidth(1.6)
    c.setFillColor(white)
    path = c.beginPath()
    px, py = tx(boundary_points_ft[0])
    path.moveTo(px, py)
    for p in boundary_points_ft[1:]:
        x, y = tx(p)
        path.lineTo(x, y)
    path.close()
    c.drawPath(path, stroke=1, fill=1)

    def draw_obstacle_shape(pts):
        c.setFillColor(HexColor("#555555"))
        c.setStrokeColor(black)
        c.setLineWidth(0.5)
        path = c.beginPath()
        x0, y0 = tx(pts[0])
        path.moveTo(x0, y0)
        for p in pts[1:]:
            x, y = tx(p)
            path.lineTo(x, y)
        path.close()
        c.drawPath(path, stroke=1, fill=1)

    for obs in obstacles or []:
        pts = obs.get("points_ft") if isinstance(obs, dict) else obs
        draw_obstacle_shape(pts)

    for room in rooms:
        pts = room["geometry_points_ft"]
        c.setFillColor(_room_color(room["room_type"]))
        c.setStrokeColor(black)
        c.setLineWidth(1.1)
        path = c.beginPath()
        x0, y0 = tx(pts[0])
        path.moveTo(x0, y0)
        for p in pts[1:]:
            x, y = tx(p)
            path.lineTo(x, y)
        path.close()
        c.drawPath(path, stroke=1, fill=1)

        page_pts = [tx(p) for p in pts]
        rw = max(p[0] for p in page_pts) - min(p[0] for p in page_pts)
        rh = max(p[1] for p in page_pts) - min(p[1] for p in page_pts)
        cx = sum(p[0] for p in pts) / len(pts)
        cy = sum(p[1] for p in pts) / len(pts)
        lx, ly = tx((cx, cy))

        seat = room.get("seat_estimate") or {}
        seat_count = seat.get("seat_count")
        name = room["display_name"].upper()
        start_size = max(min(rw, rh) * 0.11, 6)
        # Fit the name to the room's actual on-page width, rather than letting
        # it spill past the room's boundary — real rooms vary a lot in shape.
        name_lines, name_size = _fit_room_name(c, name, rw * 0.92, start_size)
        widest_line = max(c.stringWidth(ln, "Helvetica-Bold", name_size) for ln in name_lines)
        if widest_line > rw * 0.92 and room["room_type"] in ROOM_SHORT_LABEL:
            # Even the shrunk/wrapped full name still doesn't fit this room's
            # real on-page width (small support zone, long display name) —
            # fall back to a short label instead of letting it bleed outside
            # the room's own box (see ROOM_SHORT_LABEL above for why).
            name = ROOM_SHORT_LABEL[room["room_type"]]
            name_lines, name_size = _fit_room_name(c, name, rw * 0.92, start_size)
        extra = len(name_lines) - 1
        c.setFillColor(black)
        c.setFont("Helvetica-Bold", name_size)
        line_y = ly + (name_size * 0.8 if seat_count else 0) + extra * name_size * 0.55
        for i, ln in enumerate(name_lines):
            c.drawCentredString(lx, line_y - i * name_size * 1.1, ln)
        name_bottom_y = line_y - extra * name_size * 1.1
        if seat_count:
            c.setFont("Helvetica-Bold", name_size * 0.95)
            c.drawCentredString(lx, name_bottom_y - name_size * 1.2, str(seat_count))
            breakdown = seat.get("seat_breakdown", {})
            by = name_bottom_y - name_size * 2.3
            c.setFont("Helvetica", name_size * 0.62)
            for label, key in [("SOFA SLIDER", "SOFA_SLIDER"), ("FRONT LOUNGER", "LOUNGER"), ("PREMIUM RECLINER", "PREMIUM_RECLINER")]:
                if breakdown.get(key):
                    c.drawCentredString(lx, by, f"{label} : {breakdown[key]}")
                    by -= name_size * 0.85
        else:
            c.setFont("Helvetica", name_size * 0.7)
            c.drawCentredString(lx, name_bottom_y - name_size * 1.1, f"{room['area_sqft']:,.0f} SQ.FT")

    # A confirmed obstacle (typically a structural column) can legitimately
    # fall inside a room now (layout_engine.py's two-tier placement allows a
    # room to enclose a COLUMN, never any other obstacle type) — redraw any
    # obstacle whose real footprint intersects a placed room's footprint on
    # top of the room's opaque fill drawn above, so it stays visible the way
    # a real architectural drawing shows a column through a room rather than
    # hiding it underneath.
    room_polys_ft = []
    for room in rooms:
        try:
            room_polys_ft.append(Polygon(room["geometry_points_ft"]))
        except Exception:
            continue
    for obs in obstacles or []:
        pts = obs.get("points_ft") if isinstance(obs, dict) else obs
        try:
            obs_poly = Polygon(pts)
        except Exception:
            continue
        if not obs_poly.is_valid or obs_poly.area <= 0:
            continue
        if any(obs_poly.intersects(rp) for rp in room_polys_ft):
            draw_obstacle_shape(pts)

    # "Net Usage Area" sheets are a real, separate deliverable Connplex
    # actually produces (confirmed against multiple real client reference
    # PDFs, e.g. 1159-The Crossroads' "NET USAGE AREA @ 2nd Floor" and
    # 1158/1073's "..._NET USAGE AREA_..." files) — same floor plan and same
    # Area & Seat Chart as a Zoning Layout sheet, but with the real net
    # usable area called out directly on the drawing via a hatched overlay +
    # label, not just buried in the project-info block. This is a best-effort
    # match to that convention, not a traced copy — see this file's module
    # docstring.
    if "net usage area" in sheet_type.lower() and room_polys_ft:
        net_union = unary_union(room_polys_ft)
        net_area_sqft = net_union.area
        c.saveState()
        clip_path = c.beginPath()
        polys = [net_union] if net_union.geom_type == "Polygon" else list(net_union.geoms)
        for poly in polys:
            x0, y0 = tx(list(poly.exterior.coords)[0])
            clip_path.moveTo(x0, y0)
            for p in list(poly.exterior.coords)[1:]:
                x, y = tx(p)
                clip_path.lineTo(x, y)
            clip_path.close()
        c.clipPath(clip_path, stroke=0, fill=0)
        c.setStrokeColor(HexColor("#c0392b"))
        c.setLineWidth(0.5)
        hatch_step = 8
        page_pts_all = [tx(p) for p in boundary_points_ft]
        hx0 = min(p[0] for p in page_pts_all) - draw_h
        hx1 = max(p[0] for p in page_pts_all) + draw_h
        hy0 = min(p[1] for p in page_pts_all)
        hy1 = max(p[1] for p in page_pts_all)
        x = hx0
        while x < hx1:
            c.line(x, hy0, x + (hy1 - hy0), hy1)
            x += hatch_step
        c.restoreState()

        label_x = draw_x + draw_w / 2
        label_y = draw_y + draw_h * 0.5
        label = f"NET USAGE AREA = {net_area_sqft:,.0f} SQ.FT"
        c.setFont("Helvetica-Bold", 13)
        text_w = c.stringWidth(label, "Helvetica-Bold", 13)
        c.setFillColor(white)
        c.rect(label_x - text_w / 2 - 6, label_y - 6, text_w + 12, 18, stroke=0, fill=1)
        c.setStrokeColor(HexColor("#c0392b"))
        c.setLineWidth(1)
        c.rect(label_x - text_w / 2 - 6, label_y - 6, text_w + 12, 18, stroke=1, fill=0)
        c.setFillColor(HexColor("#c0392b"))
        c.drawCentredString(label_x, label_y - 1, label)

    # Overall dimension line under the drawing — real bounding-box size of the
    # confirmed region (in whichever axis now runs horizontal on the page,
    # after any rotation above), not an invented/rounded scale figure.
    page_pts = [tx(p) for p in boundary_points_ft]
    page_min_x = min(p[0] for p in page_pts)
    page_max_x = max(p[0] for p in page_pts)
    horiz_ft = (page_max_x - page_min_x) / scale
    x0, x1 = page_min_x, page_max_x
    dim_y = plan_y + dim_h * 0.45
    c.setStrokeColor(HexColor("#444444"))
    c.setLineWidth(0.5)
    c.line(x0, dim_y, x1, dim_y)
    c.line(x0, dim_y - 3, x0, dim_y + 3)
    c.line(x1, dim_y - 3, x1, dim_y + 3)
    c.setFont("Helvetica", 7.5)
    c.setFillColor(HexColor("#444444"))
    c.drawCentredString((x0 + x1) / 2, dim_y + 4, _fmt_ft_in(horiz_ft))


def render_pdf(project_meta: dict, boundary_points_ft, rooms, chart: dict, feasibility: dict, out_path: str,
                sheet_type="Zoning Layout", obstacles=None, region_meta=None):
    region_meta = region_meta or {}
    page_w, page_h = PAGE_SIZE
    c = pdfcanvas.Canvas(out_path, pagesize=PAGE_SIZE)

    sidebar_x = page_w - MARGIN - SIDEBAR_W
    plan_x, plan_y = MARGIN, MARGIN
    plan_w = sidebar_x - GAP - MARGIN
    plan_h = page_h - 2 * MARGIN

    _draw_floor_plan(c, boundary_points_ft, obstacles, rooms, plan_x, plan_y, plan_w, plan_h, sheet_type)
    c.setStrokeColor(black)
    c.setLineWidth(1)
    c.rect(plan_x, plan_y, plan_w, plan_h, stroke=1, fill=0)

    y = page_h - MARGIN
    y = _draw_general_notes(c, sidebar_x, y, SIDEBAR_W)
    y = _draw_notes(c, sidebar_x, y, SIDEBAR_W)
    y = _draw_legends(c, sidebar_x, y, SIDEBAR_W)
    y = _draw_area_seat_chart(c, sidebar_x, y, SIDEBAR_W, chart)

    revisions_top = plan_y + 210 * mm
    y2 = _draw_revisions(c, sidebar_x, revisions_top, SIDEBAR_W)
    y2 = _draw_drawing_issued(c, sidebar_x, y2, SIDEBAR_W, project_meta.get("revision", "R0"))
    y2 = _draw_key_plan(c, sidebar_x, y2, SIDEBAR_W)
    y2 = _draw_project_info(c, sidebar_x, y2, SIDEBAR_W, project_meta, region_meta)
    y2 = _draw_title_stamp(c, sidebar_x, y2, SIDEBAR_W, project_meta, sheet_type)
    _draw_company_block(c, sidebar_x, y2, SIDEBAR_W)

    c.save()
    return out_path
