    row(["TOTAL", f"{g['area_sqft']:,.0f}", zb(g["lounger"]), zb(g["sofa_slider"]), zb(g["duo_lounger"]),
         zb(g["premium_recliner"]), g["total_seats"]], bold=True, fill=HexColor("#ffd7d7"))

